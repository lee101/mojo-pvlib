"""Regenerate the coefficient tables in src/*.mojo from upstream pvlib.

    pixi run python build/gen_tables.py

Mojo has no module-level mutable state, so the constant tables that upstream
keeps as `np.array` globals are written once into host-owned buffers by
`spa_tables`, `dirint_coeffs_table` and `perez_coefficients`. The literals are
copied verbatim from pvlib; this script only reshapes them into Mojo source.
"""

import pathlib
import sys

import numpy as np
import pvlib
from pvlib import spa
from pvlib.irradiance import _get_dirint_coeffs, _get_perez_coefficients

ROOT = pathlib.Path(__file__).resolve().parent.parent
PREFIX = "mojopvlib"


def fmt(values) -> str:
    arr = np.asarray(values)
    if arr.ndim == 1:
        arr = arr.reshape(arr.shape[0], 1)
    elif arr.ndim > 2:
        arr = arr.reshape(arr.shape[0], -1)
    # a flat List[Float64]; one upstream row per line keeps it readable
    return "\n".join(
        "    " + ", ".join(repr(float(v)) for v in row) + ","
        for row in arr
    )


def spa_source() -> str:
    tables = [
        ("L0", spa.L0), ("L1", spa.L1), ("L2", spa.L2), ("L3", spa.L3),
        ("L4", spa.L4), ("L5", spa.L5),
        ("B0", spa.B0), ("B1", spa.B1),
        ("R0", spa.R0), ("R1", spa.R1), ("R2", spa.R2), ("R3", spa.R3),
        ("R4", spa.R4),
        ("NUTATION_ABCD_ARRAY", spa.NUTATION_ABCD_ARRAY),
        ("NUTATION_YTERM_ARRAY", spa.NUTATION_YTERM_ARRAY),
    ]
    header = len(tables) + 1
    parts = [f'''"""pvlib.spa coefficient tables, copied verbatim from pvlib {pvlib.__version__}.

Generated by build/gen_tables.py. Each table is written into a host-owned
float64 buffer in upstream's declaration order; the first {header} slots are a
header holding the table count and then each table's row count, so the host can
slice the buffer without knowing the layout.
"""

from types import F64


def _put(dst: F64, o: Int, data: List[Float64]) -> Int:
    for i in range(len(data)):
        dst.unsafe_store(o + i, data.unsafe_get(i))
    return o + len(data)


def spa_tables(dst: F64):
    dst.unsafe_store(0, {float(len(tables))})''']
    for name, arr in tables:
        parts.append(f"    dst.unsafe_store({1 + tables.index((name, arr))}, {float(len(arr))})")
    parts.append(f"    var o = {header}")
    for k, (name, arr) in enumerate(tables):
        # the final write to `o` is dead, and the compiler says so
        target = "o" if k < len(tables) - 1 else "_"
        parts.append(f"    {target} = _put(dst, o, [")
        parts.append(fmt(arr))
        parts.append("    ])")
    # Offsets are emitted here, not hand-written in spa.mojo, so the kernel and
    # the buffer layout cannot drift apart.
    parts.append("")
    parts.append(f"comptime SPA_N_TABLES = {len(tables)}")
    parts.append(f"comptime SPA_DATA_OFF = {header}")
    offset = header
    for name, arr in tables:
        parts.append(f"comptime {name}_OFF = {offset}")
        parts.append(f"comptime {name}_ROWS = {len(arr)}")
        offset += len(arr) * arr.shape[1]
    return "\n".join(parts) + "\n"


PEREZ_MODELS = [
    "allsitescomposite1990", "allsitescomposite1988", "sandiacomposite1988",
    "usacomposite1988", "france1988", "phoenix1988", "elmonte1988",
    "osage1988", "albuquerque1988", "albany1988",
]


def perez_model_id(model: str) -> int:
    model = model.lower()
    if model == "1990":
        model = "allsitescomposite1990"
    return PEREZ_MODELS.index(model)


def irradiance_source() -> str:
    coeffs = _get_dirint_coeffs()
    lines = [f'''"""pvlib.irradiance coefficient tables, copied verbatim from pvlib {pvlib.__version__}.

Generated by build/gen_tables.py.
"""

from types import F64, nan_


def _put(dst: F64, o: Int, data: List[Float64]) -> Int:
    for i in range(len(data)):
        dst.unsafe_store(o + i, data.unsafe_get(i))
    return o + len(data)


def dirint_coeffs_table(dst: F64):
    """DIRINT coefficient cube, indexed [kt_prime, zenith, delta_kt_prime, w]."""
    var o = 0''']
    for k, block in enumerate(coeffs):
        # the last write to `o` is dead, and the compiler says so
        target = "o" if k < len(coeffs) - 1 else "_"
        lines.append(f"    {target} = _put(dst, o, [")
        lines.append(fmt(block))
        lines.append("    ])")

    lines.append("")
    lines.append(f"comptime NUM_PEREZ_MODELS = {len(PEREZ_MODELS)}")
    lines.append("")
    lines.append("def perez_coefficients(model: Int, f1: F64, f2: F64):")
    lines.append('    """F1 and F2 coefficient rows for one of the Perez coefficient sets."""')
    for name in PEREZ_MODELS:
        F1, F2 = _get_perez_coefficients(name)
        lines.append(f"    if model == {PEREZ_MODELS.index(name)}:")
        lines.append("        for j in range(3):")
        lines.append("            f1.unsafe_store(0 * 3 + j, nan_())")
        lines.append("            f2.unsafe_store(0 * 3 + j, nan_())")
        for i, (row1, row2) in enumerate(zip(F1, F2)):
            for j, v in enumerate(row1):
                lines.append(f"        f1.unsafe_store({i + 1} * 3 + {j}, {float(v)!r})")
            for j, v in enumerate(row2):
                lines.append(f"        f2.unsafe_store({i + 1} * 3 + {j}, {float(v)!r})")
    lines.append("")
    lines.append("def perez_model_names() -> List[String]:")
    lines.append("    return [" + ", ".join(f'"{n}"' for n in PEREZ_MODELS) + "]")
    return "\n".join(lines) + "\n"


def main() -> int:
    (ROOT / "src").mkdir(exist_ok=True)
    (ROOT / "src" / "spa_tables.mojo").write_text(spa_source())
    (ROOT / "src" / "irradiance_tables.mojo").write_text(irradiance_source())
    print(f"wrote src/spa_tables.mojo and src/irradiance_tables.mojo "
          f"from pvlib {pvlib.__version__}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
